#!/usr/bin/env python3
"""Regenerate frame_vectors.h from partyline 1.0.5's own frame rules
(partyline.common: opus_duration_ms, frame_duration_ms, valid_frame,
FRAME_LIMITS) and LXST's Opus profile ceilings.

    /home/spangap/partyline-venv/bin/python gen_frame_vectors.py frame_vectors.h
"""
import random
import sys

from LXST.Codecs import Opus
from partyline import common

if len(sys.argv) > 1:
    sys.stdout = open(sys.argv[1], "w")


def carray(data):
    return "{" + ",".join(str(b) for b in data) + "}" if data else "{0}"


def us(ms):
    return -1 if ms is None else int(round(ms * 1000))


print("/* Generated by gen_frame_vectors.py from partyline.common — the reference rules. */")
print("#pragma once\n#include <cstdint>\n#include <cstddef>\n")

# Opus TOC: every TOC byte alone, and with a selection of second bytes.
print("struct TocVec { uint8_t b[2]; uint8_t n; int32_t us; };")
print("static const TocVec TOC_VECS[] = {")
for toc in range(256):
    for second in (None, 0x00, 0x01, 0x05, 0x3F, 0x40, 0xC3):
        packet = bytes([toc]) if second is None else bytes([toc, second])
        print(f"  {{{{{toc},{second or 0}}}, {len(packet)}, {us(common.opus_duration_ms(packet))}}},")
print("};\n")

# Opus profile ceilings and limits.
print("struct OpusProfileVec { uint8_t profile; uint32_t ceiling; };")
print("static const OpusProfileVec OPUS_PROFILE_VECS[] = {")
for profile in range(9):
    print(f"  {{{profile}, {Opus.profile_bitrate_ceiling(profile)}u}},")
print("};\n")

# Frame validity for every profile against a spread of frames. Only a frame's
# first three bytes matter to the rules, so a frame is stored as up to three
# prefix bytes and a length; the rest is zeros.
rng = random.Random(1)
cases = []
for name, (codec_class, argument, frame_ms, _) in common.PROFILES.items():
    codec = common.codec_byte(name)[0]
    limit = common.FRAME_LIMITS[name]
    frames = [(b"", 0), (bytes([codec]), 1), (bytes([codec, 0]), 2), (bytes([0x00, 0x00, 0x00]), 3)]
    if codec_class is common.Codec2:
        for mode in range(8):
            for body in (0, 1, 3, 4, 6, 7, 8, 12, 14, 16, 20, 30, 40, 60, 70, 80, 81, 160, 398, 399):
                frames.append((bytes([codec, mode]), 2 + body))
        frames.append((bytes([0x01, 0x06]), 82))   # Opus codec byte on a Codec2 body
    else:
        # every TOC at the full length; the length boundaries on a few TOCs
        for toc in range(256):
            lengths = (limit - 1,)
            if toc % 37 == 0 or common.opus_duration_ms(bytes([toc, 0x01])) == frame_ms:
                lengths = (1, 2, limit - 2, limit - 1, limit)
            for length in lengths:
                second = rng.randrange(256)
                frames.append((bytes([codec, toc, second][: 1 + min(length, 2)]), 1 + length))
        frames.append((bytes([0x02, 0x1B]), 22))   # Codec2 byte on an Opus body
    for prefix, length in frames:
        frame = prefix + bytes(length - len(prefix))
        cases.append((codec, frame_ms, limit, prefix, length, common.valid_frame(frame, name),
                      us(common.frame_duration_ms(frame))))

print("struct FrameVec { uint8_t codec; uint16_t frame_ms; uint16_t limit; uint8_t prefix[3]; uint8_t prefix_n; uint16_t n; bool valid; int32_t us; };")
print("static const FrameVec FRAME_VECS[] = {")
for codec, frame_ms, limit, prefix, length, valid, duration in cases:
    padded = list(prefix) + [0] * (3 - len(prefix))
    print(f"  {{{codec}, {frame_ms}, {limit}, {carray(padded)}, {len(prefix)}, {length}, "
          f"{'true' if valid else 'false'}, {duration}}},")
print("};")
