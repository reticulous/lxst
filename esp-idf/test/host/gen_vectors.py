#!/usr/bin/env python3
"""Regenerate vectors.h: msgpack encodings made by RNS's vendored umsgpack, the
encoder partyline and LXST use.

    /home/spangap/partyline-venv/bin/python gen_vectors.py vectors.h

Small values are emitted whole. Large ones (str/bin/array/map of 65535 and
more) are emitted as their first bytes, total length and FNV-1a-32 of the
whole encoding; the test rebuilds them from the content rules below.
  str  of length n: byte k is 'a' + k % 26
  bin  of length n: byte k is k & 0xff
  array of n: n × nil
  map of n: keys 0 … n-1 (ints), values nil
"""
import sys

from RNS.vendor import umsgpack

if len(sys.argv) > 1:
    sys.stdout = open(sys.argv[1], "w")


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def carray(data):
    return "{" + ",".join(str(b) for b in data) + "}" if data else "{0}"


def s_of(n):
    return "".join(chr(ord("a") + k % 26) for k in range(n))


def b_of(n):
    return bytes(k & 0xFF for k in range(n))


INTS = [0, 1, 127, 128, 255, 256, 65535, 65536, 2**32 - 1, 2**32, 2**63 - 1, 2**63, 2**64 - 1,
        -1, -31, -32, -33, -127, -128, -129, -32767, -32768, -32769, -2**31, -2**31 - 1, -2**63]
LENGTHS = [0, 1, 15, 16, 31, 32, 255, 256, 65535, 65536]
BIG = 1024   # above this, emit prefix + fnv only

print("/* Generated by gen_vectors.py with RNS.vendor.umsgpack — the reference encoder. */")
print("#pragma once\n#include <cstdint>\n#include <cstddef>\n")

print("struct IntVec { const uint8_t* b; size_t n; bool neg; uint64_t u; int64_t i; };")
for k, v in enumerate(INTS):
    print(f"static const uint8_t int_{k}[] = {carray(umsgpack.packb(v))};")
print("static const IntVec INT_VECS[] = {")
for k, v in enumerate(INTS):
    u = v if v >= 0 else 0
    i = v if v < 0 else 0
    print(f"  {{int_{k}, sizeof int_{k}, {'true' if v < 0 else 'false'}, {u}ull, {i if i != -2**63 else '-9223372036854775807LL - 1'}LL}},"
          .replace("LLLL", "LL"))
print("};\n")

print("/* kind: 's' str, 'b' bin, 'a' array of nil, 'm' map int→nil */")
print("struct SizedVec { char kind; uint32_t count; const uint8_t* b; size_t n; size_t total; uint32_t fnv; };")
sized = []
for kind in "sbam":
    for n in LENGTHS:
        if kind == "s":
            enc = umsgpack.packb(s_of(n))
        elif kind == "b":
            enc = umsgpack.packb(b_of(n))
        elif kind == "a":
            enc = umsgpack.packb([None] * n)
        else:
            enc = umsgpack.packb({k: None for k in range(n)})
        name = f"sized_{kind}_{n}"
        shown = enc if len(enc) <= BIG else enc[:8]
        print(f"static const uint8_t {name}[] = {carray(shown)};")
        sized.append((kind, n, name, len(shown), len(enc), fnv1a(enc)))
print("static const SizedVec SIZED_VECS[] = {")
for kind, n, name, shown, total, h in sized:
    print(f"  {{'{kind}', {n}u, {name}, {shown}, {total}, 0x{h:08x}u}},")
print("};\n")

FLOATS64 = [0.0, 1.5, -2.25, 1e300, 3.141592653589793]
FLOATS32 = [1.5, -0.25, 3.0e38]
print("struct FloatVec { const uint8_t* b; size_t n; bool single; double v; };")
floats = []
for k, v in enumerate(FLOATS64):
    print(f"static const uint8_t f64_{k}[] = {carray(umsgpack.packb(v))};")
    floats.append((f"f64_{k}", "false", repr(v)))
for k, v in enumerate(FLOATS32):
    print(f"static const uint8_t f32_{k}[] = {carray(umsgpack.packb(v, force_float_precision='single'))};")
    floats.append((f"f32_{k}", "true", f"(double){repr(v)}f"))
print("static const FloatVec FLOAT_VECS[] = {")
for name, single, v in floats:
    print(f"  {{{name}, sizeof {name}, {single}, {v}}},")
print("};\n")

EXTS = [(5, b"\x01"), (5, b"\x01\x02"), (-1, b"abcd"), (7, b"12345678"), (127, b"0123456789abcdef"),
        (-128, b"xyz"), (3, bytes(300)), (2, b"")]
print("struct ExtVec { const uint8_t* b; size_t n; int8_t type; uint32_t len; };")
for k, (t, d) in enumerate(EXTS):
    print(f"static const uint8_t ext_{k}[] = {carray(umsgpack.packb(umsgpack.Ext(t, d)))};")
print("static const ExtVec EXT_VECS[] = {")
for k, (t, d) in enumerate(EXTS):
    print(f"  {{ext_{k}, sizeof ext_{k}, {t}, {len(d)}u}},")
print("};\n")

SINGLES = [
    ("nil", None),
    ("true", True),
    ("false", False),
    ("ext_in_map", {1: umsgpack.Ext(5, b"abc"), 2: 7, 3: [umsgpack.Ext(1, b"x"), "after"]}),
    ("str_keys", {"name": "héllo wörld ✓", "sid": 3, "motd": "", "ver": 1, "rtt": 12.5, "hops": None}),
    ("nested", {0: [1, [2, [3, None, False]], -5, 2**40], "k": {"x": b"\x00\x01"}}),
    ("frames", {1: [b"\x02\x06" + bytes(range(80)), b"\x02\x06" + bytes(80)], 16: 65535}),
]
for name, v in SINGLES:
    enc = umsgpack.packb(v)
    print(f"static const uint8_t vec_{name}[] = {carray(enc)};")
