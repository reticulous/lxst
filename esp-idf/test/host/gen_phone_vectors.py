#!/usr/bin/env python3
"""Regenerate phone_vectors.h: LXST telephony packets packed by RNS's vendored
umsgpack (the packer LXST's signalling and packetizer use), and LXST 0.5.4's
call profiles.

    /home/spangap/partyline-venv/bin/python gen_phone_vectors.py phone_vectors.h
"""
import math
import sys

from RNS.vendor import umsgpack
from LXST.Codecs import Codec2, Opus
from LXST.Primitives.Telephony import Profiles

if len(sys.argv) > 1:
    sys.stdout = open(sys.argv[1], "w")


def carray(data):
    return "{" + ",".join(f"0x{b:02x}" for b in data) + "}"


def frame(codec, n):
    return bytes([codec]) + bytes((k * 7 + 3) & 0xFF for k in range(n - 1))


opus61 = frame(0x01, 61)
c2_82 = bytes([0x02, 0x06]) + bytes(range(80))
big = frame(0x01, 300)

# (name, python object, signals, frames)
cases = [
    ("available", {0x00: [0x03]}, [0x03], None),
    ("ringing", {0x00: [0x04]}, [0x04], None),
    ("busy", {0x00: [0x00]}, [0x00], None),
    ("rejected", {0x00: [0x01]}, [0x01], None),
    ("connecting", {0x00: [0x05]}, [0x05], None),
    ("established", {0x00: [0x06]}, [0x06], None),
    ("prefs_mq_full", {0x00: [0xFF + 0x40, 0xF0 + 0x01]}, [0x13F, 0xF1], None),
    ("prefs_ll_half", {0x00: [0xFF + 0x80, 0xF0 + 0x02]}, [0x17F, 0xF2], None),
    ("prefs_ulbw", {0x00: [0xFF + 0x10]}, [0x10F], None),
    ("bare_int", {0x00: 0x04}, [0x04], None),
    ("frame_opus", {0x01: opus61}, None, [opus61]),
    ("frame_c2", {0x01: c2_82}, None, [c2_82]),
    ("frame_list", {0x01: [opus61, c2_82]}, None, [opus61, c2_82]),
    ("frame_big", {0x01: big}, None, [big]),
    ("both", {0x00: [0x06], 0x01: opus61}, [0x06], [opus61]),
    ("extra_key", {0x00: [0x03], 0x07: {"x": [1, 2.5, None]}}, [0x03], None),
]

print("/* Generated by gen_phone_vectors.py with RNS's umsgpack and LXST 0.5.4. */")
print("#pragma once\n#include <cstdint>\n#include <cstddef>\n")
for name, obj, sigs, frames in cases:
    print(f"static const uint8_t V_{name}[] = {carray(umsgpack.packb(obj))};")
    if frames:
        for i, f in enumerate(frames):
            print(f"static const uint8_t V_{name}_f{i}[] = {carray(f)};")
print()
print("struct PhoneVec { const char* name; const uint8_t* b; size_t n; bool encode; int nsig; uint16_t sig[4];"
      " int nframes; const uint8_t* f[4]; size_t fn[4]; };")
print("static const PhoneVec PHONE_VECS[] = {")
for name, obj, sigs, frames in cases:
    enc = "true" if name not in ("bare_int", "frame_list", "both", "extra_key") else "false"
    s = sigs or []
    fr = frames or []
    sig = "{" + ",".join(str(x) for x in (s + [0] * 4)[:4]) + "}"
    fp = "{" + ",".join([f"V_{name}_f{i}" for i in range(len(fr))] + ["nullptr"] * (4 - len(fr))) + "}"
    fl = "{" + ",".join([str(len(f)) for f in fr] + ["0"] * (4 - len(fr))) + "}"
    print(f"  {{\"{name}\", V_{name}, sizeof V_{name}, {enc}, {len(s) if sigs is not None else -1}, {sig},"
          f" {len(fr) if frames is not None else -1}, {fp}, {fl}}},")
print("};\n")

C2_MODE = {Codec2.CODEC2_700C: 0x00, Codec2.CODEC2_1600: 0x04, Codec2.CODEC2_3200: 0x06}
C2_SUB = {0x00: (40, 4), 0x04: (40, 8), 0x06: (20, 8)}
print("struct RefProfile { uint8_t id; uint8_t codec; uint8_t mode; uint16_t frame_ms; uint16_t frame_bytes; uint8_t buffer; };")
print("static const RefProfile REF_PROFILES[] = {")
for p in sorted(Profiles.available_profiles()):
    c = Profiles.get_codec(p)
    ms = Profiles.get_frame_time(p)
    if isinstance(c, Codec2):
        mode = C2_MODE[c.mode]
        sub_ms, sub_b = C2_SUB[mode]
        print(f"  {{0x{p:02x}, 0x02, 0x{mode:02x}, {ms}, {2 + (ms // sub_ms) * sub_b}, {Profiles.get_buffer_frames(p)}}},")
    else:
        ceiling = Opus.profile_bitrate_ceiling(c.profile)
        nbytes = 1 + math.ceil(ceiling / 8 * ms / 1000)
        print(f"  {{0x{p:02x}, 0x01, 0x{c.profile:02x}, {ms}, {nbytes}, {Profiles.get_buffer_frames(p)}}},")
print("};")
